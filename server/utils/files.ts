import { eq } from 'drizzle-orm'
import type { H3Event } from 'h3'
import { MAX_UPLOAD_BYTES, UPLOAD_MIME_TYPES, type UploadMimeType } from '#shared/utils/constants'
import type { DbOrTx } from '../domain/db'
import {
  cleanName,
  deleteStoredFile,
  readStoredFile,
  sniffMimeType,
  storeFile,
  type FileRow,
  type StoreFileInput,
} from '../domain/storage'

export function uploadsDir(): string {
  return useRuntimeConfig().uploadsDir || './.data/uploads'
}

export interface Upload {
  data: Buffer
  filename: string
  mimeType: UploadMimeType
  /** The text fields of the same form. */
  fields: Record<string, string>
}

/**
 * Reads a multipart form: the file in the `file` field plus the text fields. The type comes from the
 * file's first bytes. 400, 413 or 415 with an Italian message when something is wrong.
 */
export async function readUpload(
  event: H3Event,
  options: { accept?: readonly UploadMimeType[]; maxBytes?: number } = {},
): Promise<Upload> {
  const maxBytes = options.maxBytes ?? MAX_UPLOAD_BYTES
  const accept = options.accept ?? UPLOAD_MIME_TYPES
  const tooBig = `Il file supera ${Math.round(maxBytes / 1024 / 1024)} MB`
  const declared = Number(getRequestHeader(event, 'content-length') ?? 0)
  if (declared > maxBytes + 256 * 1024) throw createError({ statusCode: 413, message: tooBig })

  const parts = await readMultipartFormData(event)
  const fields: Record<string, string> = {}
  let file: { data: Buffer; filename: string } | undefined
  for (const part of parts ?? []) {
    if (part.name === 'file' && part.filename) file = { data: part.data, filename: part.filename }
    else if (part.name && !part.filename) fields[part.name] = part.data.toString('utf8')
  }
  if (!file || !file.data.length) throw createError({ statusCode: 400, message: 'Nessun file ricevuto' })
  if (file.data.length > maxBytes) throw createError({ statusCode: 413, message: tooBig })
  const mimeType = sniffMimeType(file.data)
  if (!mimeType || !accept.includes(mimeType)) {
    const onlyPdf = accept.length === 1 && accept[0] === 'application/pdf'
    throw createError({
      statusCode: 415,
      message: onlyPdf ? 'Carica un file PDF' : 'Formato non supportato: carica un PDF, un JPG o un PNG',
    })
  }
  return { data: file.data, filename: cleanName(file.filename), mimeType, fields }
}

/** Stores an upload (or generated bytes) and records it in `files`. */
export function saveFile(input: StoreFileInput, db: DbOrTx = useDb()): Promise<FileRow> {
  return storeFile(db, uploadsDir(), input)
}

export function loadFile(file: Pick<FileRow, 'storageKey'>): Promise<Buffer> {
  return readStoredFile(uploadsDir(), file)
}

export function removeFile(fileId: string, db: DbOrTx = useDb()): Promise<void> {
  return deleteStoredFile(db, uploadsDir(), fileId)
}

/** Answers with a stored file, inline (preview) or as a download. Never kept by shared caches. */
export async function sendFile(
  event: H3Event,
  file: FileRow,
  options: { download?: boolean; filename?: string } = {},
): Promise<Buffer> {
  const data = await loadFile(file)
  const name = cleanName(options.filename ?? file.originalName)
  const ascii = name.replace(/[^\x20-\x7e]/g, '_')
  setResponseHeaders(event, {
    'Content-Type': file.mimeType,
    'Content-Length': String(data.byteLength),
    'Content-Disposition': `${options.download ? 'attachment' : 'inline'}; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(name)}`,
    'Cache-Control': 'private, no-store',
  })
  return data
}

/** The `files` row of an id, or 404. */
export async function requireFileRow(id: string, db: DbOrTx = useDb()): Promise<FileRow> {
  const [file] = await db.select().from(tables.files).where(eq(tables.files.id, id)).limit(1)
  if (!file) throw createError({ statusCode: 404, message: 'File non trovato' })
  return file
}
